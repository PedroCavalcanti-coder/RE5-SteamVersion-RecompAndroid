"""
gen_dispatch.py - Generate the indirect-call lookup for a lifted NE tree.

`call far [bx+4]`, `call ax`, a window procedure registered by address: the
target is a (selector, offset) pair only known at run time. Selectors are
normalised to segment numbers, so the pair names a lifted segNNN_XXXX directly,
and this emits one switch over every lifted function:

    int recomp_dispatch_lookup(CPU *cpu, uint16_t seg, uint16_t off);

It runs the function and returns 1, or returns 0 without touching the CPU. What
a MISS means is the runtime's call, not this table's: runtime/win16's
recomp_stubs.c aborts, a fuller runtime may log and unwind the frame. So this
file only answers "is there code there".

    python gen_dispatch.py --src work/src --out work/src/_dispatch.c

Upstreamed from catz/tools/gen_dispatch.py, which also emitted the
dispatch_far/dispatch_near wrappers with its own miss policy baked in.
"""
import argparse
import glob
import os
import re

DEF_RE = re.compile(r'^void (seg(\d+)_([0-9A-Fa-f]+))\(CPU \*cpu\)', re.M)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', required=True, help='directory of lifted seg*.c')
    ap.add_argument('--out', required=True, help='the .c file to write')
    args = ap.parse_args()

    out_abs = os.path.abspath(args.out)
    funcs, seen = [], set()
    for path in sorted(glob.glob(os.path.join(args.src, '*.c'))):
        # Only lifted segments: the generated _*.c files hold abort stubs for
        # calls the decoder could not align, and dispatching into one kills the
        # run where a miss would have been logged and survived.
        if os.path.abspath(path) == out_abs or os.path.basename(path).startswith('_'):
            continue
        text = open(path, encoding='utf-8', errors='replace').read()
        for name, seg, off in DEF_RE.findall(text):
            if name not in seen:
                seen.add(name)
                funcs.append(((int(seg) << 16) | int(off, 16), name))
    funcs.sort()

    L = ['/* _dispatch.c - Auto-generated by gen_dispatch.py. Do not edit. */',
         '#include "segments.h"',
         '',
         'int recomp_dispatch_lookup(CPU *cpu, uint16_t seg, uint16_t off)',
         '{',
         '    switch (((uint32_t)seg << 16) | off) {']
    L += [f'    case 0x{k:08X}u: {n}(cpu); return 1;' for k, n in funcs]
    L += ['    default: return 0;', '    }', '}', '']
    os.makedirs(os.path.dirname(out_abs), exist_ok=True)
    with open(out_abs, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L))
    print(f'Wrote {args.out}: dispatch over {len(funcs)} functions')


if __name__ == '__main__':
    main()
